    {
        $base = [
            'meta_title' => ['label' => 'Meta Title', 'type' => 'text', 'max' => 70],
            'meta_description' => ['label' => 'Meta Description', 'type' => 'textarea', 'max' => 500],
            'focus_keywords' => ['label' => 'Focus Keywords', 'type' => 'text', 'help' => 'Comma-separated'],
            'og_title' => ['label' => 'OG Title', 'type' => 'text', 'max' => 70],
            'og_description' => ['label' => 'OG Description', 'type' => 'textarea', 'max' => 200],
            'og_image' => ['label' => 'OG Image Path', 'type' => 'text'],
            'og_url' => ['label' => 'OG URL', 'type' => 'url'],
            'twitter_title' => ['label' => 'Twitter Title', 'type' => 'text', 'max' => 70],
            'twitter_description' => ['label' => 'Twitter Description', 'type' => 'textarea', 'max' => 200],
            'twitter_image' => ['label' => 'Twitter Image Path', 'type' => 'text'],
            'canonical_url' => ['label' => 'Canonical URL', 'type' => 'url'],
            'robots' => ['label' => 'Robots', 'type' => 'select', 'options' => [
                'index,follow' => 'Index, Follow',
                'noindex,follow' => 'NoIndex, Follow',
                'index,nofollow' => 'Index, NoFollow',
                'noindex,nofollow' => 'NoIndex, NoFollow',
            ]],
            'hreflang' => ['label' => 'Hreflang (JSON)', 'type' => 'textarea', 'rows' => 3],
            'schema_type' => ['label' => 'Schema Type', 'type' => 'select', 'options' => [
                'Product' => 'Product',
                'WebPage' => 'WebPage',
                'Organization' => 'Organization',
                'LocalBusiness' => 'Local Business',
                'Service' => 'Service',
                'BreadcrumbList' => 'Breadcrumb List',
                'FAQPage' => 'FAQ Page',
                'Article' => 'Article',
            ]],
            'schema_markup' => ['label' => 'Schema Markup (JSON)', 'type' => 'textarea', 'rows' => 5],
            'notes' => ['label' => 'Internal Notes', 'type' => 'textarea', 'rows' => 2],
            'status' => ['label' => 'Active', 'type' => 'toggle'],
        ];

        return $base;
    }
}
